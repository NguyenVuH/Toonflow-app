import { Database } from "bun:sqlite";
import { describe, expect, test } from "bun:test";
import { SqliteTaskRepository } from "../src/persistence";
import { runReadyWorkflow } from "../src/runtime";
import type { WorkflowGraph } from "../src/schemas/workflow";
import type { TaskRecord } from "../src/schemas/runtime";

const time = "2026-11-26T00:00:00.000Z";
const graph: WorkflowGraph = {
  workflowId: "wf-runner", version: 1, createdAt: time,
  nodes: [
    { nodeId: "a", kind: "trigger", title: "A", capability: "input", inputs: [], outputs: [{ name: "out", type: "text" }], dependsOn: [], config: {}, enabled: true },
    { nodeId: "b", kind: "tool", title: "B", capability: "transform", inputs: [{ name: "in", type: "text", required: true }], outputs: [{ name: "out", type: "text" }], dependsOn: ["a"], config: {}, enabled: true }
  ],
  edges: [{ edgeId: "e1", fromNodeId: "a", fromPort: "out", toNodeId: "b", toPort: "in", valueType: "text", autoGenerated: true }]
};

const task = (taskId: string, nodeId: string, dependencies: string[] = []): TaskRecord => ({
  taskId, nodeId, goalId: "goal", dependencies, status: "pending", attempts: 0, maxAttempts: 3,
  estimatedCostUsd: 0, actualCostUsd: 0, idempotencyKey: `${taskId}-idempotent`,
  createdAt: time, updatedAt: time
});

describe("SQLite task repository", () => {
  test("persists tasks across repository instances", () => {
    const path = ":memory:";
    const first = new SqliteTaskRepository(path);
    first.insert(task("task-a", "a"));
    expect(first.get("task-a")?.status).toBe("pending");
    first.close();
  });
});

describe("workflow runner", () => {
  test("executes only ready nodes and commits only validated outputs", async () => {
    const db = new Database(":memory:");
    const repo = new SqliteTaskRepository(":memory:");
    repo.insert(task("task-a", "a"));
    repo.insert(task("task-b", "b", ["task-a"]));
    const result = await runReadyWorkflow({
      graph, goalId: "goal", repository: repo, workerId: "worker-1", concurrency: 2,
      now: () => "2026-11-26T00:01:00.000Z",
      execute: async nodeId => ({ output: { nodeId }, costUsd: 0 }),
      validate: async (_nodeId, output) => ({ valid: !!output, errors: [] })
    });
    expect(result.succeeded).toEqual(["task-a"]);
    expect(repo.get("task-a")?.status).toBe("succeeded");
    expect(repo.get("task-b")?.status).toBe("pending");
    repo.close();
    db.close();
  });

  test("does not commit invalid worker output", async () => {
    const repo = new SqliteTaskRepository(":memory:");
    repo.insert(task("task-a", "a"));
    const result = await runReadyWorkflow({
      graph: { ...graph, nodes: [graph.nodes[0]], edges: [] }, goalId: "goal",
      repository: repo, workerId: "worker-1", concurrency: 1,
      now: () => "2026-11-26T00:01:00.000Z",
      execute: async () => ({ output: null, costUsd: 0 }),
      validate: async () => ({ valid: false, errors: ["missing artifact"] })
    });
    expect(result.failed).toEqual(["task-a"]);
    expect(repo.get("task-a")?.status).toBe("retry_wait");
    repo.close();
  });
});
