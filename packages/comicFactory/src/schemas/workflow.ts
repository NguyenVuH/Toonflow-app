import { z } from "zod";

export const workflowValueTypeSchema = z.enum([
  "text", "json", "rule_snapshot", "series_bible", "chapter_plan", "entity",
  "asset", "image", "dialogue", "panel", "page", "chapter", "file", "boolean"
]);
export const workflowNodeKindSchema = z.enum([
  "trigger", "llm", "tool", "condition", "parallel", "merge", "validator", "renderer", "publish"
]);
export const workflowNodeSchema = z.object({
  nodeId: z.string().min(1).max(128),
  kind: workflowNodeKindSchema,
  title: z.string().min(1).max(200),
  capability: z.string().min(1).max(128),
  inputs: z.array(z.object({ name: z.string().min(1), type: workflowValueTypeSchema, required: z.boolean().default(true), semanticKey: z.string().optional() }).strict()),
  outputs: z.array(z.object({ name: z.string().min(1), type: workflowValueTypeSchema, semanticKey: z.string().optional() }).strict()),
  dependsOn: z.array(z.string().min(1)).default([]),
  config: z.record(z.string(), z.json()).default({}),
  instructionRef: z.string().optional(),
  enabled: z.boolean().default(true)
}).strict();

export const workflowEdgeSchema = z.object({
  edgeId: z.string().min(1),
  fromNodeId: z.string().min(1),
  fromPort: z.string().min(1),
  toNodeId: z.string().min(1),
  toPort: z.string().min(1),
  valueType: workflowValueTypeSchema,
  autoGenerated: z.boolean().default(false)
}).strict();

export const workflowGraphSchema = z.object({
  workflowId: z.string().min(1),
  version: z.number().int().positive(),
  nodes: z.array(workflowNodeSchema),
  edges: z.array(workflowEdgeSchema),
  createdAt: z.string().datetime()
}).strict();

export type WorkflowNode = z.infer<typeof workflowNodeSchema>;
export type WorkflowEdge = z.infer<typeof workflowEdgeSchema>;
export type WorkflowGraph = z.infer<typeof workflowGraphSchema>;
